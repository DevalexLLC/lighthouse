// Generates web/src/assets/worldPath.ts: the dashboard's world outline as a
// single pre-projected SVG path. One-time dev tooling (same category as
// `npm ci` / `make vendor`) — the OUTPUT is committed and release builds
// never run this or fetch anything.
//
// Source data: Natural Earth 1:110m "land" (public domain), as GeoJSON.
// One-time acquisition on a dev box with network, then:
//
//   curl -sSLo /tmp/ne_110m_land.json \
//     https://raw.githubusercontent.com/martynafford/natural-earth-geojson/master/110m/physical/ne_110m_land.json
//   node web/tools/build-world-path.mjs /tmp/ne_110m_land.json > web/src/assets/worldPath.ts
//
// Projection: equirectangular into a 720×300 viewBox — lon −180..180 → x
// 0..720, lat 90..−60 → y 0..300 (Antarctica cropped). WorldMap.tsx uses the
// SAME transform for site dots, so the outline and markers can never drift.
// Rings are simplified with Douglas–Peucker in projected space (no mapshaper
// dependency) and rounded to 1 decimal.

import { readFileSync } from 'node:fs'

const VIEW_W = 720
const VIEW_H = 300
const LAT_TOP = 90
const LAT_BOTTOM = -60 // crop below 60°S: Antarctica is not probe territory
const EPSILON = 0.45 // Douglas–Peucker tolerance, viewBox px
const MIN_RING_AREA = 2.5 // drop islands smaller than this many px²

const project = ([lon, lat]) => [
  ((lon + 180) / 360) * VIEW_W,
  ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * VIEW_H,
]

// Perpendicular distance of p from segment a–b.
function perpDist(p, a, b) {
  const dx = b[0] - a[0]
  const dy = b[1] - a[1]
  const len2 = dx * dx + dy * dy
  if (len2 === 0) return Math.hypot(p[0] - a[0], p[1] - a[1])
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len2))
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy))
}

function douglasPeucker(points, eps) {
  if (points.length < 3) return points
  let maxDist = 0
  let index = 0
  const last = points.length - 1
  for (let i = 1; i < last; i++) {
    const d = perpDist(points[i], points[0], points[last])
    if (d > maxDist) {
      maxDist = d
      index = i
    }
  }
  if (maxDist <= eps) return [points[0], points[last]]
  const left = douglasPeucker(points.slice(0, index + 1), eps)
  const right = douglasPeucker(points.slice(index), eps)
  return left.slice(0, -1).concat(right)
}

function ringArea(points) {
  let area = 0
  for (let i = 0; i < points.length; i++) {
    const [x1, y1] = points[i]
    const [x2, y2] = points[(i + 1) % points.length]
    area += x1 * y2 - x2 * y1
  }
  return Math.abs(area / 2)
}

const input = process.argv[2]
if (!input) {
  console.error('usage: node build-world-path.mjs <ne_110m_land.geojson>')
  process.exit(2)
}
const geo = JSON.parse(readFileSync(input, 'utf8'))

const rings = []
for (const feature of geo.features) {
  const g = feature.geometry
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []
  for (const poly of polys) {
    // Outer ring only: 110m land has no holes worth 720px-wide rendering.
    const ring = poly[0]
    if (ring.every(([, lat]) => lat < LAT_BOTTOM)) continue // Antarctica
    let pts = ring.map(project).map(([x, y]) => [x, Math.min(y, VIEW_H)])
    pts = douglasPeucker(pts, EPSILON)
    if (pts.length < 4 || ringArea(pts) < MIN_RING_AREA) continue
    rings.push(pts)
  }
}

const fmt = (n) => {
  const s = n.toFixed(1)
  return s.endsWith('.0') ? s.slice(0, -2) : s
}
let path = ''
let ringCount = 0
for (const pts of rings) {
  let d = ''
  let prev = null
  for (const p of pts) {
    const key = fmt(p[0]) + ',' + fmt(p[1])
    if (key === prev) continue
    d += (d === '' ? 'M' : 'L') + key
    prev = key
  }
  if (d.split('L').length < 3) continue
  path += d + 'Z'
  ringCount++
}

process.stdout.write(`// Generated by web/tools/build-world-path.mjs — do not hand-edit.
// Source: Natural Earth 1:110m land (public domain), Antarctica cropped,
// Douglas–Peucker simplified, equirectangular-projected. ${ringCount} rings.
// lon −180..180 → x 0..${VIEW_W}; lat ${LAT_TOP}..${LAT_BOTTOM} → y 0..${VIEW_H} — keep in sync
// with project() in components/WorldMap.tsx.
export const WORLD_VIEW_W = ${VIEW_W}
export const WORLD_VIEW_H = ${VIEW_H}
export const WORLD_LAT_TOP = ${LAT_TOP}
export const WORLD_LAT_BOTTOM = ${LAT_BOTTOM}
export const WORLD_PATH =
  '${path}'
`)
console.error(`world path: ${rings.length} rings, ${path.length} bytes`)
